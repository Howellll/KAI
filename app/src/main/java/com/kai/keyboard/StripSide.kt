package com.kai.keyboard

/**
 * Где в полосе подсказок стоит угловая кнопка: кнопка ИИ, а пока ИИ выключен — кнопка поиска эмодзи.
 * Настройка владельца («Слева» / «Справа») уступает режиму одной рукой: там кнопка примыкает к той же
 * стороне, куда сдвинуты клавиши, — иначе она оказывалась бы у пустого края.
 */
object StripSide {
    /**
     * @param oneHand 0 — режим выключен, 1 — клавиши у левого края, 2 — у правого.
     * @param prefRight настройка «Положение кнопок ИИ/AI»: true — справа.
     * @param panel открыта панель (эмодзи, буфер, сейф): полосы подсказок там нет — кнопки тоже.
     * @return true — кнопка у правого края.
     */
    fun right(oneHand: Int, prefRight: Boolean, panel: Boolean): Boolean = when {
        panel -> false
        oneHand == 1 -> false
        oneHand == 2 -> true
        else -> prefRight
    }

    /**
     * Надпись на кнопке: на английской раскладке «AI», на русской «ИИ».
     * Отличие только визуальное — нажатие делает одно и то же.
     */
    fun label(lang: Lang): String = if (lang == Langs.EN) "AI" else "ИИ"
}
